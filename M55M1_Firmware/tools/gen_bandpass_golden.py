"""
gen_bandpass_golden.py — 產生 M55M1 韌體 band-pass 的 golden vector 與係數,
並驗證「C 端簡單雙向 biquad(無 filtfilt padding)」是否足以重現訓練的 filtfilt。

背景:訓練/inference.py 的前處理在 z-score 前有一道
    butter(3, [0.5,40]/(500/2), 'band') + filtfilt(零相位、前後雙向)
M55M1 韌體(NN_ModelInference/af_inference.h 的 bandpass_0p5_40)必須重現它。
因整段 15000 點已收齊,韌體可做批次「正向掃→反向掃」的 IIR 重現零相位特性。

本腳本:
  1. 印出 butter(3) 的 b/a 與 second-order-sections(SOS,給 CMSIS-DSP arm_biquad 用)。
  2. 對真實擷取視窗算 filtfilt(golden 參考)與 naive 雙向 sosfilt(C 端可行做法),
     比較兩者誤差,並比對【模型最終 AF 機率】是否改變。
  3. 輸出 golden vector(輸入 + filtfilt 期望輸出)給韌體對拍。

用法: python gen_bandpass_golden.py [window.npy]
"""
import os, sys
import numpy as np
from scipy.signal import butter, filtfilt, sosfilt, sosfilt_zi, tf2sos
try:
    sys.stdout.reconfigure(encoding="utf-8")  # 避免 Windows gbk 對 emoji 崩潰
except Exception:
    pass

FS = 500
BP_LOW, BP_HIGH = 0.5, 40.0
HERE = os.path.dirname(__file__)
DEFAULT_WIN = os.path.join(HERE, "..", "..", "captures", "ecg_uart", "window_0s_30s.npy")

WIN = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_WIN
x = np.load(WIN).astype(np.float64)
print(f"[input] {os.path.basename(WIN)}  len={len(x)}  raw ADC {x.min():.0f}~{x.max():.0f}")

# ── 係數 ──
b, a = butter(3, [BP_LOW/(FS/2), BP_HIGH/(FS/2)], "band")
sos = tf2sos(b, a)
np.set_printoptions(precision=10, suppress=True)
print("\n=== butter(3) 傳遞函數係數 ===")
print("b =", b)
print("a =", a)
print("\n=== SOS(second-order sections,給 CMSIS-DSP arm_biquad_cascade_df2T_f64)===")
print("每列 = [b0 b1 b2 a0 a1 a2],共", sos.shape[0], "個 biquad")
print(sos)

# ── golden 參考:filtfilt(與訓練完全一致)──
ref = filtfilt(b, a, x)

rms = np.sqrt(np.mean(ref**2))

def report(name, cand):
    err = np.abs(ref - cand)
    print(f"\n=== filtfilt(golden) vs {name} ===")
    print(f"  max abs err   = {err.max():10.4f}   ({100*err.max()/rms:7.3f}% of RMS)")
    print(f"  mean abs err  = {err.mean():10.4f}   ({100*err.mean()/rms:7.4f}% of RMS)")
    print(f"  邊界 max err  = 前50:{err[:50].max():.2f}  後50:{err[-50:].max():.2f}")
    print(f"  內部 max err(去頭尾500點)= {err[500:-500].max():.4f}")
    return err

# 做法 A:naive,零初始條件、不去 DC(最陽春,示範為何不夠)
def cand_naive(sig):
    y = sosfilt(sos, sig)
    return sosfilt(sos, y[::-1])[::-1]

# 做法 B【建議】:先去均值 + 每個 pass 用穩態初始條件(sosfilt_zi × 首樣本)→ 貼近 filtfilt
def cand_good(sig):
    m = sig.mean()
    s = sig - m
    zi = sosfilt_zi(sos)
    y, _ = sosfilt(sos, s, zi=zi * s[0])
    y = y[::-1]
    y, _ = sosfilt(sos, y, zi=zi * y[0])
    return y[::-1]

cand = cand_good(x)                    # 用於後續模型比對
report("做法A: naive 零初始(不去DC)", cand_naive(x))
report("做法B: 去均值+穩態初始(建議)", cand)

# ── 最關鍵:兩種前處理最終模型輸出是否改變 ──
def zscore_quant(sig):
    mu, sd = sig.mean(), sig.std()
    sig = (sig - mu) / sd if sd > 1e-6 else sig - mu
    return sig
try:
    try:
        from ai_edge_litert.interpreter import Interpreter
    except ImportError:
        from tensorflow.lite import Interpreter
    MP = os.path.join(HERE, "..", "..", "ECG_classification", "deploy", "model_int8.tflite")
    it = Interpreter(model_path=MP); it.allocate_tensors()
    ind, outd = it.get_input_details()[0], it.get_output_details()[0]
    insc, inzp = ind["quantization"]; osc, ozp = outd["quantization"]
    def run(sig):
        s = zscore_quant(sig)
        q = np.clip(np.round(s/insc + inzp), -128, 127).astype(np.int8).reshape(ind["shape"])
        it.set_tensor(ind["index"], q); it.invoke()
        o = it.get_tensor(outd["index"])[0].astype(np.float32)
        return (o - ozp) * osc
    p_ref, p_cand = run(ref), run(cand)
    print("\n=== 模型輸出比對(這才是重點)===")
    print(f"  filtfilt 版 : N={p_ref[0]:.3f} AF={p_ref[1]:.3f} O={p_ref[2]:.3f}")
    print(f"  做法B  版 : N={p_cand[0]:.3f} AF={p_cand[1]:.3f} O={p_cand[2]:.3f}")
    print(f"  AF 機率差 = {abs(p_ref[1]-p_cand[1]):.4f}  → "
          f"{'✅ 可忽略,C 端用 naive 雙向即可' if abs(p_ref[1]-p_cand[1])<0.02 else '⚠️ 有差,需比對 padding'}")
except Exception as e:
    print(f"\n[跳過模型比對] {e}")

# ── 輸出 golden vector(給韌體 host 端單元測試對拍)──
out_h = os.path.join(HERE, "bandpass_golden.h")
N = len(x)
with open(out_h, "w", encoding="ascii") as f:
    f.write("// Auto-generated by gen_bandpass_golden.py - band-pass golden vector\n")
    f.write("// Firmware bandpass_0p5_40() output should match GOLDEN_EXPECTED (interior err < ~0.1% of RMS)\n")
    f.write(f"// filter: butter(3,[0.5,40]/(500/2),'band') + filtfilt  |  N={N}\n")
    f.write("#ifndef BANDPASS_GOLDEN_H\n#define BANDPASS_GOLDEN_H\n\n")
    f.write(f"#define GOLDEN_N {N}\n\n")
    f.write("static const float GOLDEN_SOS[3][6] = {\n")
    for row in sos:
        f.write("  {" + ",".join(f"{v:.10f}f" for v in row) + "},\n")
    f.write("};\n\n")
    # 穩態初始條件(做法B 每個 biquad 的 zi,需 × 該 pass 的首樣本值)
    zi = sosfilt_zi(sos)
    f.write("// Steady-state init: at each pass start, state = GOLDEN_ZI[section] * first_sample\n")
    f.write("static const float GOLDEN_ZI[3][2] = {\n")
    for row in zi:
        f.write("  {" + ",".join(f"{v:.10f}f" for v in row) + "},\n")
    f.write("};\n\n")
    f.write("static const float GOLDEN_INPUT[GOLDEN_N] = {\n")
    f.write(",".join(f"{v:.1f}f" for v in x))
    f.write("\n};\n\n")
    f.write("static const float GOLDEN_EXPECTED[GOLDEN_N] = {\n")
    f.write(",".join(f"{v:.6f}f" for v in ref))
    f.write("\n};\n\n#endif\n")
print(f"\n[written] {out_h}  ({os.path.getsize(out_h)//1024} KB)")
